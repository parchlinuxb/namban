# DoH goes through dnscrypt-proxy (systemd-resolved can't do DoH) on a port that
# neither resolved (127.0.0.53/54:53) nor a distro dnscrypt-proxy (:53) uses.
DNSCRYPT_BIN = "/usr/bin/dnscrypt-proxy"
DNSCRYPT_CONF = "/etc/namban/dnscrypt-proxy.toml"
DNSCRYPT_UNIT = "namban-dnscrypt.service"
DNSCRYPT_LISTEN = "127.0.0.1:5053"
DOH_URL_MARKER = "# namban-doh-url: "


def doh_stamp(url: str, ip: Optional[str] = None) -> str:
    """Encode a DoH server as a DNS stamp (https://dnscrypt.info/stamps-specifications)."""
    import base64, struct, urllib.parse
    # The URL is written into a root-owned TOML file: no quotes, whitespace or control chars
    if any(c in url for c in "'\"\\") or any(c.isspace() or not c.isprintable() for c in url):
        raise ValueError(f"Invalid characters in DoH URL: {url!r}")
    u = urllib.parse.urlsplit(url)
    if u.scheme != "https" or not u.hostname:
        raise ValueError(f"Not an https:// DoH URL: {url}")
    lp = lambda s: bytes([len(s.encode())]) + s.encode()
    host = u.netloc.rsplit("@", 1)[-1]  # keeps an explicit :port
    raw = (b"\x02" + struct.pack("<Q", 0) + lp(ip or "") + b"\x00"  # props, addr, no cert hashes
           + lp(host) + lp(u.path or "/dns-query"))
    return "sdns://" + base64.urlsafe_b64encode(raw).decode().rstrip("=")


def dnscrypt_config(url: str, ip: Optional[str] = None) -> str:
    """dnscrypt-proxy config with a single static DoH upstream."""
    import ipaddress
    try:
        ip = str(ipaddress.ip_address(ip)) if ip else None
    except ValueError:
        ip = None  # a hostname: dnscrypt-proxy resolves it via bootstrap_resolvers
    return "\n".join([
        "# Generated by Namban DNS Manager",
        f"{DOH_URL_MARKER}{url}",
        f"listen_addresses = ['{DNSCRYPT_LISTEN}']",
        "server_names = ['namban']",
        "require_dnssec = false",
        "require_nolog = false",
        "require_nofilter = false",
        "bootstrap_resolvers = ['9.9.9.11:53', '8.8.8.8:53']",
        "",
        "[static.'namban']",
        f"stamp = '{doh_stamp(url, ip)}'",
        "",
    ])


def _set_dnscrypt(toolbox: BaseToolBox, config: Optional[str]) -> None:
    """Run the DoH forwarder with this config, or stop it and remove its config (None)."""
    if config is None:
        toolbox.execute(['systemctl', 'disable', '--now', DNSCRYPT_UNIT])
        toolbox.remove(DNSCRYPT_CONF)
    else:
        toolbox.mkdir(str(Path(DNSCRYPT_CONF).parent))
        toolbox.write(DNSCRYPT_CONF, config)
        # Enabled so it is back after a reboot; resolved's drop-in points at it
        toolbox.execute(['systemctl', 'enable', DNSCRYPT_UNIT])
        toolbox.execute(['systemctl', 'restart', DNSCRYPT_UNIT])


class ApplyDNSProfile(BaseAction):
    """Action to apply a DNS profile using systemd drop-in configuration with automatic rollback capability."""
    
    DROPIN_DIR = "/etc/systemd/resolved.conf.d"
    DEFAULT_CONF_PATH = "/etc/systemd/resolved.conf.d/namban.conf"
    
    def __init__(self, profile: DNSProfile, resolved_conf_path: str = DEFAULT_CONF_PATH):
        self.profile = profile
        self.resolved_conf_path = resolved_conf_path
    
    def do(self, toolbox: BaseToolBox) -> dict:
        """Apply DNS profile via drop-in and save previous state for rollback."""
        doh = next((s for s in self.profile.servers if s.dns_type == DNSType.DOH), None)
        if doh and not toolbox.exists(DNSCRYPT_BIN):
            raise ValueError("DNS over HTTPS needs dnscrypt-proxy installed")
        # Built before touching anything, so a bad DoH URL changes nothing
        dnscrypt_new = dnscrypt_config(doh.doh_url or "", doh.primary) if doh else None
        new_config = self._generate_resolved_conf(self.profile)

        # Ensure drop-in directory exists
        toolbox.mkdir(self.DROPIN_DIR)
        
        config_before = None
        if toolbox.exists(self.resolved_conf_path):
            config_before = toolbox.read(self.resolved_conf_path)
        dnscrypt_before = toolbox.read(DNSCRYPT_CONF) if toolbox.exists(DNSCRYPT_CONF) else None

        # The forwarder must be up before resolved is pointed at it
        if dnscrypt_new:
            _set_dnscrypt(toolbox, dnscrypt_new)
        
        # Write new drop-in config
        toolbox.write(self.resolved_conf_path, new_config)
        
        # Reload systemd-resolved
        toolbox.execute(['systemctl', 'reload-or-restart', 'systemd-resolved'])
        if not dnscrypt_new and dnscrypt_before is not None:
            _set_dnscrypt(toolbox, None)
        
        return {
            'profile_name': self.profile.name,
            'config_before': config_before,
            'resolved_conf_path': self.resolved_conf_path,
            'dnscrypt_before': dnscrypt_before
        }
    
    @classmethod
    def undo(cls, state: dict, toolbox: BaseToolBox) -> None:
        """Restore previous DNS configuration by removing drop-in or restoring previous content."""
        config_before = state.get('config_before')
        resolved_conf_path = state.get('resolved_conf_path', cls.DEFAULT_CONF_PATH)
        dnscrypt_before = state.get('dnscrypt_before')
        if dnscrypt_before is not None:
            _set_dnscrypt(toolbox, dnscrypt_before)
        
        if config_before is not None:
            toolbox.write(resolved_conf_path, config_before)
        else:
            # If no drop-in existed before, remove the drop-in file
            if toolbox.exists(resolved_conf_path):
                toolbox.remove(resolved_conf_path)
        
        # Reload systemd-resolved to apply changes
        toolbox.execute(['systemctl', 'reload-or-restart', 'systemd-resolved'])
        if dnscrypt_before is None and toolbox.exists(DNSCRYPT_CONF):
            _set_dnscrypt(toolbox, None)
    
    def _generate_resolved_conf(self, profile: DNSProfile) -> str:
        """Generate systemd-resolved drop-in content from DNS profile."""
        lines = ["# Generated by Namban DNS Manager", "[Resolve]"]
        dns_servers = []
        is_dot = any(s.dns_type == DNSType.DOT for s in profile.servers)

        if any(s.dns_type == DNSType.DOH for s in profile.servers):
            # resolved can't speak DoH; it forwards plain DNS to the local dnscrypt-proxy
            return '\n'.join(lines + [f"DNS={DNSCRYPT_LISTEN}", "Domains=~.", "DNSSEC=allow-downgrade", "Cache=yes", ""])

        for server in profile.servers:
            hostname_suffix = f"#{server.tls_hostname}" if (is_dot and server.tls_hostname) else ""
            dns_servers.append(f"{server.primary}{hostname_suffix}")
            if server.secondary:
                dns_servers.append(f"{server.secondary}{hostname_suffix}")
        if dns_servers:
            lines.append(f"DNS={' '.join(dns_servers)}")

        # Force global DNS routing for all queries over per-link DHCP DNS
        lines.append("Domains=~.")

        if is_dot:
            lines.append("DNSOverTLS=yes")

        lines.extend(["DNSSEC=allow-downgrade", "Cache=yes", ""])
        return '\n'.join(lines)


class BackupDNSConfig(BaseAction):
    """Action to backup current DNS configuration."""
    
    def __init__(self, source: str = ApplyDNSProfile.DEFAULT_CONF_PATH, 
                 backup_path: Optional[str] = None):
        self.source = source
        self.backup_path = backup_path or "/var/lib/namban/resolved.conf.backup"
    
    def do(self, toolbox: BaseToolBox) -> dict:
        """Backup DNS config through privileged daemon."""
        if toolbox.exists(self.source):
            config_content = toolbox.read(self.source)
        else:
            config_content = ""
        
        # Ensure backup directory exists using toolbox (privileged)
        backup_dir = str(Path(self.backup_path).parent)
        toolbox.mkdir(backup_dir)
        
        # Write backup through toolbox
        toolbox.write(self.backup_path, config_content)
        
        return {
            'source': self.source,
            'backup_path': self.backup_path,
            'original_existed': toolbox.exists(self.source)
        }
    
    @classmethod
    def undo(cls, state: dict, toolbox: BaseToolBox) -> None:
        """Remove backup file through privileged daemon."""
        backup_path = state.get('backup_path')
        if toolbox.exists(backup_path):
            toolbox.remove(backup_path)

