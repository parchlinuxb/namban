"""DNS-specific action classes for reversible DNS configuration changes."""

import json
import subprocess
from pathlib import Path
from typing import Optional
from .actions import BaseAction
from .toolbox import BaseToolBox
from models import DNSProfile, DNSType


class ApplyDNSProfile(BaseAction):
    """Action to apply a DNS profile using systemd drop-in configuration with automatic rollback capability."""
    
    DROPIN_DIR = "/etc/systemd/resolved.conf.d"
    DEFAULT_CONF_PATH = "/etc/systemd/resolved.conf.d/namban.conf"
    
    def __init__(self, profile: DNSProfile, resolved_conf_path: str = DEFAULT_CONF_PATH):
        self.profile = profile
        self.resolved_conf_path = resolved_conf_path
    
    def do(self, toolbox: BaseToolBox) -> dict:
        """Apply DNS profile via drop-in and save previous state for rollback."""
        # Ensure drop-in directory exists
        toolbox.mkdir(self.DROPIN_DIR)
        
        config_before = None
        if toolbox.exists(self.resolved_conf_path):
            config_before = toolbox.read(self.resolved_conf_path)
        
        # Stop any existing DoH service before applying new configuration
        toolbox.execute(['systemctl', 'stop', 'namban-doh@*'])
        
        # Check if DoH is requested
        is_doh = any(s.dns_type == DNSType.DOH for s in self.profile.servers)
        doh_service_name = None
        
        if is_doh:
            doh_server = next((s for s in self.profile.servers if s.dns_type == DNSType.DOH), None)
            if doh_server and doh_server.doh_url:
                # Escape URL for systemd template instance
                escaped_url = subprocess.run(
                    ['systemd-escape', doh_server.doh_url],
                    capture_output=True, text=True, check=False
                ).stdout.strip() or "default"
                doh_service_name = f"namban-doh@{escaped_url}.service"
                toolbox.execute(['systemctl', 'start', doh_service_name])
        
        # Generate new drop-in config from profile
        new_config = self._generate_resolved_conf(self.profile)
        
        # Write new drop-in config
        toolbox.write(self.resolved_conf_path, new_config)
        
        # Reload systemd-resolved
        toolbox.execute(['systemctl', 'reload-or-restart', 'systemd-resolved'])
        
        return {
            'profile_name': self.profile.name,
            'config_before': config_before,
            'resolved_conf_path': self.resolved_conf_path,
            'doh_service_name': doh_service_name
        }
    
    @classmethod
    def undo(cls, state: dict, toolbox: BaseToolBox) -> None:
        """Restore previous DNS configuration by removing drop-in or restoring previous content."""
        config_before = state.get('config_before')
        resolved_conf_path = state.get('resolved_conf_path', cls.DEFAULT_CONF_PATH)
        doh_service_name = state.get('doh_service_name')
        
        # Stop DoH service if one was running
        if doh_service_name:
            toolbox.execute(['systemctl', 'stop', doh_service_name])
        else:
            toolbox.execute(['systemctl', 'stop', 'namban-doh@*'])
        
        if config_before is not None:
            toolbox.write(resolved_conf_path, config_before)
        else:
            # If no drop-in existed before, remove the drop-in file
            if toolbox.exists(resolved_conf_path):
                toolbox.remove(resolved_conf_path)
        
        # Reload systemd-resolved to apply changes
        toolbox.execute(['systemctl', 'reload-or-restart', 'systemd-resolved'])
    
    def _generate_resolved_conf(self, profile: DNSProfile) -> str:
        """Generate systemd-resolved drop-in content from DNS profile."""
        lines = ["# Generated by Namban DNS Manager", "[Resolve]"]
        dns_servers = []
        is_doh = any(s.dns_type == DNSType.DOH for s in profile.servers)
        is_dot = any(s.dns_type == DNSType.DOT for s in profile.servers)

        if is_doh:
            # Route to local DoH stub forwarder
            lines.append("DNS=127.0.0.54:53")
        else:
            for server in profile.servers:
                hostname_suffix = f"#{server.tls_hostname}" if (is_dot and server.tls_hostname) else ""
                dns_servers.append(f"{server.primary}{hostname_suffix}")
                if server.secondary:
                    dns_servers.append(f"{server.secondary}{hostname_suffix}")
            if dns_servers:
                lines.append(f"DNS={' '.join(dns_servers)}")

        # Force global DNS routing for all queries over per-link DHCP DNS
        lines.append("Domains=~.")

        if is_dot:
            lines.append("DNSOverTLS=yes")

        lines.extend(["DNSSEC=allow-downgrade", "Cache=yes", ""])
        return '\n'.join(lines)


class BackupDNSConfig(BaseAction):
    """Action to backup current DNS configuration."""
    
    def __init__(self, source: str = ApplyDNSProfile.DEFAULT_CONF_PATH, 
                 backup_path: Optional[str] = None):
        self.source = source
        self.backup_path = backup_path or "/var/lib/namban/resolved.conf.backup"
    
    def do(self, toolbox: BaseToolBox) -> dict:
        """Backup DNS config through privileged daemon."""
        if toolbox.exists(self.source):
            config_content = toolbox.read(self.source)
        else:
            config_content = ""
        
        # Ensure backup directory exists using toolbox (privileged)
        backup_dir = str(Path(self.backup_path).parent)
        toolbox.mkdir(backup_dir)
        
        # Write backup through toolbox
        toolbox.write(self.backup_path, config_content)
        
        return {
            'source': self.source,
            'backup_path': self.backup_path,
            'original_existed': toolbox.exists(self.source)
        }
    
    @classmethod
    def undo(cls, state: dict, toolbox: BaseToolBox) -> None:
        """Remove backup file through privileged daemon."""
        backup_path = state.get('backup_path')
        if toolbox.exists(backup_path):
            toolbox.remove(backup_path)

